class HeIsGoingAcrossAHillIntransitivePartOfSpeechStringSpec extends GroovyTestCase {

	static def verbName = new Stemmer()

	static {
		verbName.habitual = new DefinitionLine(syllabary: "ᏕᎦᎶᎨᎵᏐᎢ")
		verbName.imperative = new DefinitionLine(syllabary: "ᏘᎶᎨᎷᎦ")
		verbName.infinitive = new DefinitionLine(syllabary: "ᏧᎶᎨᎸᏍᏗ")
		verbName.present1st = new DefinitionLine(syllabary: "ᏕᏥᎶᎨᎵ")
		verbName.present3rd = new DefinitionLine(syllabary: "ᏕᎦᎶᎨᎵ")
		verbName.remotepast = new DefinitionLine(syllabary: "ᏚᎶᎨᎴᏒᎢ")
	}


	private String conj(String subject) {
		def verb = Conjugate.createVerbToConjugate(subject, "SG3AN", verbName,
		"PRESENT", PartOfSpeech.VERB_INTRANSITIVE.toString(), false)
		return Conjugate.conjugate(verb).wholeWord
	}

