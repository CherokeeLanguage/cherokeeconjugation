import net.cherokeedictionary.util.PrefixTableSubject
import net.cherokeedictionary.verb.conjugation.Conjugate

class HeIsRunningIntransitivePartOfSpeechStringSpec extends GroovyTestCase {

	static def verbName = new Stemmer()

	static {
		verbName.habitual = new DefinitionLine(syllabary: "ᏓᏍᏆᎵᏗᏍᎪᎢ")
		verbName.imperative = new DefinitionLine(syllabary: "ᏘᏍᏆᎵᏓ")
		verbName.infinitive = new DefinitionLine(syllabary: "ᏧᏍᏆᎵᏙᏗ")
		verbName.present1st = new DefinitionLine(syllabary: "ᏕᏥᏍᏆᎵᏗᎭ")
		verbName.present3rd = new DefinitionLine(syllabary: "ᏓᏍᏆᎵᏗᎭ")
		verbName.remotepast = new DefinitionLine(syllabary: "ᏚᏍᏆᎵᏔᏅᎢ")
	}


	private String conj(String subject) {
		def verb = Conjugate.createVerbToConjugate(subject, "SG3AN", verbName,
		"PRESENT", PartOfSpeech.VERB_INTRANSITIVE.toString(), false)
		return Conjugate.conjugate(verb).wholeWord
	}

